// Deploys SimpleStorage and writes the address + ABI to public/contract-config.js
// so the frontend always uses the contract you just deployed.
const fs = require("fs");
const path = require("path");
const hre = require("hardhat");

async function main() {
  const { ethers, network, artifacts } = hre;
  const [deployer] = await ethers.getSigners();
  console.log(`Network:  ${network.name}`);
  console.log(`Deployer: ${deployer.address}`);

  const Factory = await ethers.getContractFactory("SimpleStorage");
  const contract = await Factory.deploy();
  await contract.waitForDeployment();
  const address = await contract.getAddress();
  console.log(`SimpleStorage deployed to: ${address}`);

  const { chainId } = await ethers.provider.getNetwork();
  const artifact = await artifacts.readArtifact("SimpleStorage");

  const config = {
    address,
    chainId: Number(chainId),
    networkName: network.name,
    abi: artifact.abi,
  };

  const out = path.join(__dirname, "..", "public", "contract-config.js");
  fs.writeFileSync(
    out,
    "// Auto-generated by scripts/deploy.js. Do not edit by hand.\n" +
      "window.CONTRACT_CONFIG = " + JSON.stringify(config, null, 2) + ";\n"
  );
  console.log(`Frontend config written to ${path.relative(process.cwd(), out)}`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
